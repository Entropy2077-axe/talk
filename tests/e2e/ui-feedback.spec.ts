test('old API preference migrates to one selected configuration', async ({ page }) => {
  await page.addInitScript(() => {
    const configs = ['one', 'two'].map((id) => ({ id, name: id, provider: 'custom', apiKey: '', baseUrl: `https://${id}.example/v1`, model: id, utilityModel: id, sampling: {}, createdAt: 1, updatedAt: 1 }))
    localStorage.setItem('talk-settings', JSON.stringify({ version: 30, state: { aiApiConfigs: configs, aiApiFailoverOrder: ['two', 'one'], aiProvider: 'custom', apiKey: '', baseUrl: 'https://one.example/v1', model: 'one', utilityModel: 'one' } }))
  })
  await page.goto('/#/settings/api-configurations')
  await expect(page.getByLabel('当前 API', { exact: true })).toHaveValue('two')
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('talk-settings')!).state)
  expect(persisted.activeAiApiConfigId).toBe('two')
  expect(persisted).not.toHaveProperty('aiApiFailoverOrder')
})
