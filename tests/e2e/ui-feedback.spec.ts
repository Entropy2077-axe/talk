import { expect, test, type Page } from 'playwright/test'

async function open(page: Page, path: string) {
  await page.goto(`/#${path}`)
  await expect(page.locator('.app-shell')).toBeVisible()
  await page.evaluate(async () => {
    const { useSettingsStore } = await import('/src/store/useSettingsStore.ts')
    useSettingsStore.getState().setSettings({ apiKey: '', experienceMode: 'free', animationsEnabled: false })
  })
}

test('discover separates albums, worldbooks live in world selection, and account combines balance and salary', async ({ page }) => {
  await open(page, '/discover')
  await expect(page.getByText('查看朋友动态，进入当前启用的功能。')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '资料库', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '相册', exact: true }).click()
  await expect(page.getByRole('heading', { name: '相册', exact: true })).toBeVisible()
  await page.goto('/#/library?view=worldview')
  await expect(page).toHaveURL(/#\/save-load$/)
  await expect(page.getByRole('button', { name: '编辑当前世界书' })).toBeVisible()
  await page.goto('/#/library?view=album')
  await expect(page).toHaveURL(/#\/album$/)
  await page.goto('/#/me')
  await expect(page.getByText('当前世界 / 切换世界', { exact: true })).toHaveCount(0)
  const panel = page.getByText('我的余额', { exact: true }).locator('../..')
  await expect(panel.getByText('今日工资', { exact: true })).toBeVisible()
  const balance = await panel.getByText('我的余额').boundingBox()
  const salary = await panel.getByText('今日工资').boundingBox()
  expect(balance!.x).toBeLessThan(salary!.x)
})

