test('models use inline dropdowns and the API selection persists', async ({ page }) => {
  await open(page, '/settings/api-configurations')
  await page.evaluate(async () => {
    const { useSettingsStore } = await import('/src/store/useSettingsStore.ts')
    const config = useSettingsStore.getState().aiApiConfigs[0]
    useSettingsStore.getState().setSettings({ aiApiConfigs: [{ ...config, id: 'first', name: '第一个 API', apiKey: '' }, { ...config, id: 'second', name: '第二个 API', apiKey: '', model: 'custom-model' }], activeAiApiConfigId: 'first' })
  })
  await page.reload()
  await page.getByLabel('当前 API', { exact: true }).selectOption('second')
  await expect(page.getByLabel('聊天模型', { exact: true })).toHaveValue('custom-model')
  await page.getByLabel('聊天模型', { exact: true }).selectOption('__manual__')
  await page.getByLabel('聊天模型名称').fill('another-model')
  await page.getByRole('button', { name: '保存配置', exact: true }).click()
  await page.reload()
  await expect(page.getByLabel('当前 API', { exact: true })).toHaveValue('second')
  await expect(page.getByLabel('聊天模型', { exact: true })).toHaveValue('another-model')
  await expect(page.getByText(/按顺序自动尝试|备用接口|主 API/)).toHaveCount(0)
})

test('location details directly create a child and remove unused form controls', async ({ page }) => {
  await open(page, '/locations')
  await page.getByRole('button', { name: '回到当前位置', exact: true }).click()
  const building = page.getByTestId('location-building').filter({ hasText: '我的家' })
  await building.click()
  await page.getByRole('button', { name: '新建子地点', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建子地点', exact: true })
  await expect(dialog).toBeVisible()
  await expect(page.getByText('编辑地点', { exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '保存子地点', exact: true }).click()
  await expect(dialog.getByText('请填写子地点名称', { exact: true })).toBeVisible()
  await expect(dialog.getByText('请填写子地点名称', { exact: true })).toHaveCount(0, { timeout: 6000 })
  await dialog.getByLabel('子地点名称').fill('测试新房间')
  await dialog.getByLabel('子地点描述').fill('安静的书房')
  await dialog.getByRole('button', { name: '保存子地点', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('测试新房间', { exact: true })).toBeVisible()
  const child = await page.evaluate(async () => {
    const { db } = await import('/src/db/db.ts')
    return (await db.locations.toArray()).find((item) => item.name === '测试新房间')
  })
  expect(child?.parentId).toBeTruthy()
  expect(child).not.toHaveProperty('access')
  for (const name of ['编辑', '删除地点', '关闭地点详情']) {
    expect((await page.getByRole('button', { name, exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
  }
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(page.getByText('个人备注', { exact: true })).toHaveCount(0)
  await expect(page.getByText('访问权限', { exact: true })).toHaveCount(0)
  await expect(page.getByPlaceholder('搜索公寓、医院、公园……')).toHaveCount(0)
})

